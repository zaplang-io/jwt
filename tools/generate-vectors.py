#!/usr/bin/env python3
"""Reproduce committed known-answer fixtures using Python stdlib, not Zap."""
import base64
import hashlib
import hmac
import json
from pathlib import Path

def b64(data):
    return base64.urlsafe_b64encode(data).decode().rstrip('=')

out = ['# Generated by tools/generate-vectors.py (Python stdlib HMAC/SHA-2).',
       '# Verification preserves original whitespace/member order in signed bytes.',
       'import jwt', '', 'def main():']
for alg, size, digest in [('HS256', 32, hashlib.sha256), ('HS512', 64, hashlib.sha512)]:
    key = b'0123456789abcdef' * (size // 16)
    header = '{"typ":"JWT", "alg":"' + alg + '"}'
    payload = '{ "sub": "alice", "nested": {"roles": ["admin", "user"]}, "label": "café 😀" }'
    message = b64(header.encode()) + '.' + b64(payload.encode())
    token = message + '.' + b64(hmac.new(key, message.encode(), digest).digest())
    # Also pin encode output with a single claim; headers use insertion order.
    encoded = b64(('{"alg":"'+alg+'","typ":"JWT"}').encode()) + '.' + b64(b'{"sub":"alice"}')
    encoded += '.' + b64(hmac.new(key, encoded.encode(), digest).digest())
    q = lambda s: json.dumps(s, ensure_ascii=False)
    out += [f'    auto key{size} = bytes({q(key.decode())})',
            f'    auto token{size} = {q(token)}',
            f'    auto verified{size} = jwt.verify_signature(token{size}, key{size}, "{alg}")',
            f'    assert json.dumps(verified{size}.claims["sub"]) == "\\\"alice\\\""',
            f'    assert jwt.encode({{"sub": JsonValue.Str("alice")}}, key{size}, "{alg}") == {q(encoded)}']
out += ['    print("independent vectors: PASS")', '']
Path(__file__).resolve().parents[1].joinpath('tests/vectors_test.zap').write_text('\n'.join(out))
